export const TIMELINE_POINTS = [
  -13800000000, -4500000000, -250000000, -20000, -2560, -500, -44, 1000, 1492, 1789, 1905, 1947, 1969, 1989, 2026, 2050, 2100, 2500, 5000, 10000
];

export function getEraByYear(year: number): HistoricalEra {
  // Find exact or closest era
  const exact = HISTORICAL_ERAS.find((e) => e.year === year);
  if (exact) return exact;

  // Find closest
  let closest = HISTORICAL_ERAS[0];
  let minDiff = Math.abs(year - closest.year);
  for (const era of HISTORICAL_ERAS) {
    const diff = Math.abs(year - era.year);
    if (diff < minDiff) {
      minDiff = diff;
      closest = era;
    }
  }

  // If synthetic interpolation needed, return modified closest
  if (Math.abs(year - closest.year) > 0) {
    const isFuture = year > 2026;
    return {
      ...closest,
      year: year,
      eraName: isFuture ? `Temporal Horizon: Year ${year} (Future Projection)` : `Temporal Epoch: Year ${year}`,
      tagline: isFuture ? "AI-GENERATED FUTURE SCENARIO (SPECULATIVE SIMULATION)" : `Historical timeline inspection at Year ${year}`,
      description: isFuture
        ? `Speculative trajectory computed for Year ${year} based on algorithmic projections of energy, robotics, and social governance.`
        : `Archival coordinates aligned with global historical dynamics of Year ${year}. Explore artifacts and query TEMPUS for deep archival records.`,
      epochTag: isFuture 
        ? "SPECULATIVE_FUTURE" 
        : year < -2000000000 
          ? "COSMIC" 
          : year < -20000 
            ? "PREHISTORIC" 
            : year < 500 
              ? "ANCIENT" 
              : year < 1500 
                ? "MEDIEVAL" 
                : year < 1900 
                  ? "INDUSTRIAL" 
                  : year < 2000 
                    ? "ATOMIC" 
                    : "DIGITAL"
    };
  }

  return closest;
}
